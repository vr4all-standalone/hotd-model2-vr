std::vector<uint8_t> bytes(const std::filesystem::path& path) {
    std::ifstream input(path,std::ios::binary);assert(input);
    return {std::istreambuf_iterator<char>(input),std::istreambuf_iterator<char>()};
}
uint32_t word(const std::vector<uint8_t>& data,uint32_t byte,unsigned size=4) {
    assert(uint64_t(byte)+size<=data.size());uint32_t result=0;
    for(unsigned i=0;i<size;i++)result|=uint32_t(data[byte+i])<<(i*8);
    return result;
}
bool close(float value,float expected){return std::abs(value-expected)<0.000001f;}
void inspect_materials(const NativeWeapon& gun,const std::filesystem::path& capture,const std::filesystem::path& output) {
    NativeFrame frame;
    for(const char* name:{"texture0","texture1","palette","colorxlat","luma","gamma"})
        frame.blobs.push_back({name,bytes(capture/(std::string(name)+".bin"))});
    Model2Resources resources(frame);assert(resources.valid());
    constexpr int size=600,width=size*2,height=size;
    std::vector<uint32_t> pixels(width*height,0xffe1e4e9);
    std::vector<double> depth(width*height,1e30);
    std::set<uint32_t> colors;unsigned painted=0;
    for(int pane=0;pane<2;pane++)for(const auto& face:gun.polygons) {
        NativePolygon material;material.luma=255;
        for(unsigned i=0;i<4;i++)material.header[i]=face.header[i];
        std::array<std::array<double,3>,4> points;
        for(unsigned i=0;i<face.count;i++) {
            const auto& v=face.vertices[i];
            const double x=-v.y*(pane?.85:1)+v.x*(pane?.53:0),y=v.z,z=v.x*(pane?.85:1)+v.y*(pane?.53:0);
            points[i]={pane*size+65+x*215,400-y*215,z};
        }
        for(unsigned triangle=1;triangle+1<face.count;triangle++) {
            const unsigned ids[]={0,triangle,triangle+1};
            auto a=points[ids[0]],b=points[ids[1]],c=points[ids[2]];
            const double determinant=(b[1]-c[1])*(a[0]-c[0])+(c[0]-b[0])*(a[1]-c[1]);
            if(std::abs(determinant)<1e-10)continue;
            const int x0=std::max(pane*size,int(std::floor(std::min({a[0],b[0],c[0]})))),
                x1=std::min((pane+1)*size-1,int(std::ceil(std::max({a[0],b[0],c[0]})))),
                y0=std::max(0,int(std::floor(std::min({a[1],b[1],c[1]})))),
                y1=std::min(height-1,int(std::ceil(std::max({a[1],b[1],c[1]}))));
            for(int y=y0;y<=y1;y++)for(int x=x0;x<=x1;x++) {
                const double w0=((b[1]-c[1])*(x+.5-c[0])+(c[0]-b[0])*(y+.5-c[1]))/determinant,
                    w1=((c[1]-a[1])*(x+.5-c[0])+(a[0]-c[0])*(y+.5-c[1]))/determinant,w2=1-w0-w1;
                if(w0<0||w1<0||w2<0)continue;
                const double weights[]={w0,w1,w2};double z=0,u=0,v=0;
                for(unsigned i=0;i<3;i++){z+=weights[i]*points[ids[i]][2];u+=weights[i]*face.vertices[ids[i]].u/8;v+=weights[i]*face.vertices[ids[i]].v/8;}
                const unsigned at=y*width+x;if(z>=depth[at])continue;
                const auto color=resources.sample(material,float(u),float(v),1,x,y);if(!color)continue;
                depth[at]=z;pixels[at]=*color;colors.insert(*color);painted++;
            }
        }
    }
    assert(painted>20000 && colors.size()>8);
    std::ofstream image(output,std::ios::binary);assert(image);image<<"P6\n"<<width<<" "<<height<<"\n255\n";
    for(uint32_t pixel:pixels){const char rgb[]={char(pixel>>16),char(pixel>>8),char(pixel)};image.write(rgb,3);}
    std::cout<<"Original capture materials rendered: "<<painted<<" samples, "<<colors.size()<<" colors\n";
}
int main(int argc,char** argv) {
    assert(argc==2||argc==3);const std::filesystem::path root=argv[1];
    auto program=bytes(root/"program.bin"),data=bytes(root/"main-data.bin"),
         polygons=bytes(root/"polygons.bin"),textures=bytes(root/"textures.bin");
    auto read_program=[&](uint32_t address){return address>=0x2000000?word(data,address-0x2000000):word(program,address);};
    auto read_polygon=[&](uint32_t index){return word(polygons,index*4);};
    auto read_texture=[&](uint32_t index){return word(textures,index*2,2);};
    const auto extract=[&](unsigned weapon=1,uint32_t polygon_words=0x800000,uint32_t texture_words=0x800000){
        return extract_native_weapon(read_program,read_polygon,read_texture,weapon,polygon_words,texture_words);
    };
    // Removing the HOTD adapter or retaining a VC2 table must fail this real
    // owned-ROM fixture. Literal counts/coordinates were independently decoded
    // from original hotdo's named PN_ter00a, not generated by this extractor.
    const auto gun=extract();
    assert(gun.valid && gun.weapon==1 && gun.model==0x719 && gun.object==0x8e7f31);
    assert(gun.polygons.size()==50);
    const auto& first=gun.polygons.front();assert(first.count==4 && first.attr==0x1000601);
    assert(first.header[0]==0x40c9 && first.header[1]==0x60 && first.header[2]==0xdd6 && first.header[3]==0x540);
    assert(close(first.vertices[0].x,-0.3876372874f));
    assert(close(first.vertices[0].y,-0.1303658485f));
    assert(close(first.vertices[0].z,0.2159447372f));
    assert(first.vertices[0].u==144 && first.vertices[0].v==464);
    assert(gun.polygons[16].count==3 && gun.polygons[25].count==3);
    // Triangle strip continuation must duplicate p2 into p3. Keeping the ROM's
    // unused p3 injects a false vertex at the origin into the following quad.
    assert(close(gun.polygons[17].vertices[1].x,-0.7355414033f));
    assert(close(gun.polygons[17].vertices[1].y,-1.223793149f));
    const auto& muzzle=gun.polygons[45];
    assert(muzzle.count==4 && close(muzzle.vertices[0].y,-2.258136511f));
    assert(close(muzzle.vertices[2].z,0.909589589f));
    for(unsigned unsupported:{0u,2u,3u,4u,5u,6u,7u,~0u})assert(!extract(unsupported).valid);
    assert(!extract(1,0,0x800000).valid && !extract(1,0x800000,0).valid);
    assert(!extract(1,0xe8135,0x800000).valid); // Original object's terminator is outside the capture.
    assert(!extract(1,0x800000,0x977de).valid);
    auto reject_changed=[&](std::vector<uint8_t>& region,uint32_t at){
        const uint8_t saved=region[at];region[at]^=1;assert(!extract().valid);region[at]=saved;
    };
    reject_changed(program,0x13fd0); // Unknown table/revision.
    reject_changed(program,0xb47f0); // Character skeleton must identify this pistol.
    reject_changed(data,0xe54560); // Native model name.
    reject_changed(data,0xe7a6c8); // Exact model object pointer.
    const auto polygon_at=uint32_t(0xe7f31*4);
    const auto saved=std::array<uint8_t,4>{polygons[polygon_at],polygons[polygon_at+1],polygons[polygon_at+2],polygons[polygon_at+3]};
    polygons[polygon_at]=0;polygons[polygon_at+1]=0;polygons[polygon_at+2]=0xc0;polygons[polygon_at+3]=0x7f;
    assert(!extract().valid); // NaN geometry cannot be uploaded.
    std::copy(saved.begin(),saved.end(),polygons.begin()+polygon_at);
    assert(selectable_gun_choice(AutoOriginalGun));
    auto choice=select_weapon(AutoOriginalGun,0);
    assert(choice.manual_choice==8 && choice.native_weapon==1 && choice.standard_fallback);
    assert(select_weapon(0,0).manual_choice==0 && select_weapon(1,0).manual_choice==1);
    assert(cycle_gun_choice(1,1)==AutoOriginalGun && cycle_gun_choice(AutoOriginalGun,1)==0);
    if(argc==3)inspect_materials(gun,argv[2],root/"native-pistol.ppm");
    std::cout<<"Verified HOTD scene pistol: original hotdo PN_ter00a,50 native polygons; revision, bounds, finite geometry and selection guards pass\n";
}
